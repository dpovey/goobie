package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strings"
)

const maxArity = 22

func main() {
	output := flag.String("output", "", "generated Go file")
	flag.Parse()
	if *output == "" {
		fmt.Fprintln(os.Stderr, "-output is required")
		os.Exit(2)
	}

	source, err := generate(maxArity)
	if err != nil {
		fmt.Fprintf(os.Stderr, "generate rows: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, source, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write rows: %v\n", err)
		os.Exit(1)
	}
}

func generate(maximum int) ([]byte, error) {
	var source strings.Builder
	source.WriteString("// Code generated by rowgen; DO NOT EDIT.\n\n")
	source.WriteString("package read\n\n")

	for arity := 1; arity <= maximum; arity++ {
		writeRow(&source, arity)
	}

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return nil, fmt.Errorf("format source: %w", err)
	}
	return bytes.Clone(formatted), nil
}

func writeRow(source *strings.Builder, arity int) {
	typeName := fmt.Sprintf("Row%d", arity)
	columnLabel := "columns"
	if arity == 1 {
		columnLabel = "column"
	}
	typeParameters := joinIndexed(arity, "T%d", ", ")
	fields := joinIndexed(arity, "\tV%d T%d\n", "")
	fieldPointers := joinIndexed(arity, "&result.V%d", ", ")
	arguments := joinIndexed(arity, "value.V%d", ", ")

	fmt.Fprintf(source, "// %s is a typed positional row with %d %s.\n", typeName, arity, columnLabel)
	fmt.Fprintf(source, "type %s[%s any] struct {\n%s}\n\n", typeName, typeParameters, fields)
	fmt.Fprintf(source, "// Reader returns a reader for %s.\n", typeName)
	fmt.Fprintf(source, "func (%s[%s]) Reader() Read[%s[%s]] {\n", typeName, typeParameters, typeName, typeParameters)
	fmt.Fprintf(source, "\treturn NewReader(func(scan RowScan) (%s[%s], error) {\n", typeName, typeParameters)
	fmt.Fprintf(source, "\t\tvar result %s[%s]\n", typeName, typeParameters)
	fmt.Fprintf(source, "\t\tif err := scan(%s); err != nil {\n", fieldPointers)
	fmt.Fprintf(source, "\t\t\treturn %s[%s]{}, err\n", typeName, typeParameters)
	source.WriteString("\t\t}\n\t\treturn result, nil\n\t})\n}\n\n")
	fmt.Fprintf(source, "// Map reads %d %s and transforms the row into R.\n", arity, columnLabel)
	fmt.Fprintf(source, "func (r %s[%s]) Map[R any](f func(%s) R) Read[R] {\n", typeName, typeParameters, typedArguments(arity))
	fmt.Fprintf(source, "\treturn r.Reader().Map(func(value %s[%s]) R {\n", typeName, typeParameters)
	fmt.Fprintf(source, "\t\treturn f(%s)\n", arguments)
	source.WriteString("\t})\n}\n\n")
}

func joinIndexed(count int, pattern string, separator string) string {
	parts := make([]string, count)
	for i := range count {
		index := i + 1
		if strings.Count(pattern, "%d") == 2 {
			parts[i] = fmt.Sprintf(pattern, index, index)
		} else {
			parts[i] = fmt.Sprintf(pattern, index)
		}
	}
	return strings.Join(parts, separator)
}

func typedArguments(count int) string {
	parts := make([]string, count)
	for i := range count {
		parts[i] = fmt.Sprintf("T%d", i+1)
	}
	return strings.Join(parts, ", ")
}
